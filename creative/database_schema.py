"""SQLAlchemy Core metadata for the creative domain in PostgreSQL.

The legacy ``.runtime/creative/creative.db`` SQLite store declares 36 tables.
The published migration plan described 24 business tables plus one control
table; the remaining 13 prompt template/governance/market/AB tables,
``creative_project_prompt_bindings``, ``creative_project_prompt_settings`` and
``creative_mode_migration_compensations`` are live data and are carried over
too, so every legacy row has a PostgreSQL home and nothing is silently dropped.

Type mapping from the legacy SQLite DDL:

* ``INTEGER PRIMARY KEY AUTOINCREMENT`` -> ``BIGINT GENERATED BY DEFAULT AS IDENTITY``
* epoch ``REAL`` timestamps -> ``TIMESTAMPTZ``
* ``*_json`` ``TEXT`` -> ``JSONB``
* 0/1 ``INTEGER`` flags -> ``BOOLEAN``
* ``REAL`` measurements -> ``DOUBLE PRECISION`` (never ``NUMERIC``: rounding
  would make the SQLite -> PostgreSQL -> SQLite round trip lossy)

Every constraint that the legacy schema expressed through ``UNIQUE`` clauses,
partial unique indexes and ``CHECK`` clauses is declared here with a stable
name, because the importer and the repositories address them by name.
"""

from __future__ import annotations

from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Column,
    DateTime,
    ForeignKey,
    Identity,
    Index,
    Integer,
    MetaData,
    Table,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import DOUBLE_PRECISION, JSONB, UUID


CREATIVE_METADATA = MetaData()


def _jsonb(name: str, *, default: str | None = None, nullable: bool = False) -> Column[Any]:
    """JSON column carrying the legacy SQLite text default as a JSONB default."""
    return Column(
        name,
        JSONB,
        nullable=nullable,
        server_default=None if default is None else text(f"'{default}'::jsonb"),
    )


def _created_updated() -> tuple[Column[Any], Column[Any]]:
    """Legacy epoch ``created_at``/``updated_at`` pair, both NOT NULL."""
    return (
        Column("created_at", DateTime(timezone=True), nullable=False),
        Column("updated_at", DateTime(timezone=True), nullable=False),
    )


def _bigint_pk() -> Column[Any]:
    return Column("id", BigInteger, Identity(always=False), primary_key=True)


